import assert from 'node:assert/strict';
globalThis.window = { matchMedia: () => ({ matches: false }) };
globalThis.document = { querySelector: () => null, querySelectorAll: () => [], addEventListener: () => {} };
globalThis.localStorage = { removeItem: () => {} };
const { accountRightsMarkup, normalizeAccountRights, reconcileAccountLifecycleEvent } = await import('./clientAccountRights.js');

assert.equal(normalizeAccountRights(null).state, 'guest');
assert.equal(normalizeAccountRights({ accountDeactivated: true, deletionDueAt: '2026-10-17T12:00:00.000Z' }).state, 'pending');
assert.equal(normalizeAccountRights({ accountDeactivated: false }).state, 'active');
assert.match(accountRightsMarkup({ state: 'active' }), /DOWNLOAD MY DATA/);
assert.match(accountRightsMarkup({ state: 'active' }), /DELETE ACCOUNT/);
assert.match(accountRightsMarkup({ state: 'pending', dueAt: '2026-10-17T12:00:00.000Z' }), /DELETION PENDING/);
assert.doesNotMatch(accountRightsMarkup({ state: 'guest' }), /DELETE ACCOUNT/);
assert.doesNotMatch(accountRightsMarkup({ state: 'active' }), /OPEN OPERATOR CONSOLE/);
assert.match(accountRightsMarkup({ state: 'active', isAdmin: true }), /OPEN OPERATOR CONSOLE/);
assert.match(accountRightsMarkup({ state: 'active', isAdmin: true }), /PARLOR OPERATIONS/);
assert.doesNotMatch(accountRightsMarkup({ state: 'guest', isAdmin: true }), /OPEN OPERATOR CONSOLE/);
const target = { account: { account: { username: 'owner', accountDeactivated: false } } };
reconcileAccountLifecycleEvent({ state: 'deletion-pending', dueAt: '2026-10-17T12:00:00.000Z' }, target);
assert.equal(target.account.account.accountDeactivated, true);
assert.equal(target.account.account.deletionDueAt, '2026-10-17T12:00:00.000Z');
reconcileAccountLifecycleEvent({ state: 'deletion-cancelled' }, target);
assert.equal(target.account.account.accountDeactivated, false);
target.profiles = [{ id: 'p' }];
target.achievementRecords = new Map([['a', 'now']]);
target.unlockedAchievements = new Set(['a']);
reconcileAccountLifecycleEvent({ state: 'deleted' }, target);
assert.equal(target.account, null);
assert.deepEqual(target.profiles, []);
assert.equal(target.achievementRecords.size, 0);
console.log('client account rights: 12 passed, 0 failed');
