import assert from "node:assert/strict";

globalThis.window = { matchMedia: () => ({ matches: false, addEventListener() {} }) };
const { tradeDeedActionHTML, deedManagementActionsHTML, authoritativeBuildingLevel, contextualSellMode } = await import("./clientDeedDetailUi.js");
const { popupCardHTML } = await import("./clientPopupUi.js");
const { popIconHTML } = await import("./clientPopupUi.js");
const { tileSupportsInspection } = await import("./clientTileInteraction.js");
const { state } = await import("./clientState.js");
const { deedCurrentRentLabel } = await import("./clientDeedsRender.js");
state.serverTiles = [{ index: 1, currentRent: 77 }];
assert.equal(deedCurrentRentLabel({ i: 1, kind: "property", group: "brown" }, 2), "$77 / TURN", "current rent uses the server quote rather than a stale local schedule");
state.serverTiles = [];

assert.equal(authoritativeBuildingLevel({ houseCount: 2 }, 0), 2, "server building count overrides stale client zero");
assert.equal(authoritativeBuildingLevel({ houseCount: 0 }, 2), 0, "server zero prevents a stale client building from blocking deed sale");
assert.equal(authoritativeBuildingLevel({}, 2), 2, "local count remains the fallback without a server projection");
assert.equal(contextualSellMode(2), "sell-house");
assert.equal(contextualSellMode(1), "sell-house");
assert.equal(contextualSellMode(0), "sell-deed");

const tile = { i: 1, kind: "property", name: "BOARDWALK", price: 60, group: "blue", rent: 2 };
const available = tradeDeedActionHTML({ mine: true, action: { enabled: true } });
assert.match(available, />SELL DEED</);
assert.match(available, /id="dd-trade-deed"/);
assert.match(available, /agree on the price/i);
assert.doesNotMatch(available, /\+\$|bank sale|50%/i);
const managementRow = deedManagementActionsHTML('<button id="dd-mortgage">MORTGAGE</button>', available);
assert.match(managementRow, /^<div class="dd-deed-actions">[\s\S]*id="dd-mortgage"[\s\S]*id="dd-trade-deed"[\s\S]*dd-context-note[\s\S]*<\/div>$/);
assert.match(tradeDeedActionHTML({ mine: true, action: { enabled: false, reason: "Clear the color set first." } }), /disabled/);
assert.match(tradeDeedActionHTML({ mine: true, action: { enabled: false, reason: "Clear the color set first." } }), /Clear the color set first/);
assert.equal(tradeDeedActionHTML({ mine: false, action: { enabled: true } }), "");
assert.match(tradeDeedActionHTML({ mine: true, action: { enabled: true }, label: "SELL DEED" }), />SELL DEED</);
const missingProjection = tradeDeedActionHTML({ mine: true, action: null });
assert.match(missingProjection, /disabled/);
assert.match(missingProjection, /Property trade is unavailable right now/);
assert.doesNotMatch(missingProjection, /\+\$|CONFIRM/);

const owner = { id: "p2", name: "Rival", color: "#fff" };
const prison = { i: 30, kind: "corner-go-jail", name: "GO TO PRISON" };
const prisonIcon = popIconHTML(prison);
assert.match(prisonIcon, /<svg[^>]*viewBox="0 0 16 10"/);
assert.doesNotMatch(prisonIcon, /PRISON|q-mark/, "reference glyph does not render a word wider than its icon container");
assert.match(popupCardHTML({ tile: prison, owner: null, buyable: false, unowned: false, level: 0 }), /GO TO PRISON/, "reference title retains the tile name");
assert.equal(tileSupportsInspection(prison), false, "prison corner remains noninteractive on the board");
assert.equal(tileSupportsInspection({ kind: "property" }), true, "deed inspection remains enabled");
for (const kind of ["chance", "tax", "chest"]) {
  const inspector = popupCardHTML({ tile: { ...tile, kind }, owner, buyable: false, unowned: false, level: 0 });
  assert.doesNotMatch(inspector, />OWNER</, `${kind} inspector omits ownership statistics`);
  assert.match(inspector, /SPECIAL EFFECT/);
}
const ownedProperty = popupCardHTML({ tile, owner: { id: "p1", name: "You", color: "#fff" }, buyable: true, unowned: false, level: 0 });
assert.match(ownedProperty, /data-deed-open="1"/, "owned board tile still links directly to its manager");
console.log("deed sale and tile inspector UI checks passed");

state.flights = { enabled: true, defaultFare: 85, maxFee: 200, options: [] };
state.serverTiles = [{ index: 5, departureFee: 0, arrivalFee: 140 }];
const airport = { i: 5, kind: "railroad", name: "ACC AIRPORT", price: 200 };
const inspector = popupCardHTML({ tile: airport, owner, buyable: true, unowned: false, level: 0 });
assert.match(inspector, /DEPARTURE \$0/);
assert.match(inspector, /ARRIVAL \$140/);
assert.match(inspector, /STANDARD FARE \$85/);
assert.doesNotMatch(inspector, /data-airport-fee=/, "tile inspection never edits another owner's fees");
state.serverTiles = [{ index: 5 }];
assert.match(popupCardHTML({ tile: airport, owner, buyable: true, unowned: false, level: 0 }), /DEPARTURE \$85 · ARRIVAL \$85/, "missing fee overrides use the server's standard fare");
state.flights.enabled = false;
assert.doesNotMatch(popupCardHTML({ tile: airport, owner, buyable: true, unowned: false, level: 0 }), /FLIGHT FEES/, "disabled flights do not expose irrelevant fees");

const { renderDeedDetail } = await import("./clientDeedDetailUi.js");
const { TILES } = await import("./clientBoardData.js");
const property = TILES.find(entry => entry.kind === "property");
let markup = "";
globalThis.document = { querySelector: () => ({ addEventListener() {}, querySelectorAll: () => [], set innerHTML(value) { markup = value; } }) };
state.players = [{ id: "p1", cash: 2000 }];
state.owners = { [property.i]: "p1" };
state.deedDetail = property.i;
state.houses = {};
state.mortgaged = { [property.i]: true };
state.serverTiles = [{ index: property.i, houseCount: 0, propertyActions: { unmortgage: { enabled: true, cost: 33 }, tradeDeed: { enabled: true } } }];
renderDeedDetail();
assert.match(markup, /dd-is-mortgaged/);
assert.match(markup, /dd-mortgage-status[\s\S]*<svg[\s\S]*MORTGAGED · RENT PAUSED/, "mortgage state carries a lock shape and explicit status");
assert.match(markup, /dd-redeem/);
assert.match(markup, /UNMORTGAGE \$33/);
state.mortgaged = {};
state.serverTiles = [{ index: property.i, houseCount: 5, propertyActions: { sellHouse: { enabled: true, cost: 25 } } }];
renderDeedDetail();
assert.match(markup, />HOTEL BUILT</);
assert.match(markup, />SELL HOTEL</);
assert.doesNotMatch(markup, /dd-mortgage-status|dd-redeem/);
console.log("airport fee and deed state regressions passed");
